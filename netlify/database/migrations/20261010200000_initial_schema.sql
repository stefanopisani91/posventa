-- Posventa: returns (withdrawals) and legal-warranty claims for a small online shop.
-- Catalogue, customers and orders would normally come from the shop platform;
-- here they hold fictional demo data.

CREATE TABLE products (
  id           INTEGER PRIMARY KEY,
  sku          TEXT NOT NULL UNIQUE,
  name         TEXT NOT NULL,
  brand        TEXT NOT NULL,
  category     TEXT NOT NULL,
  price_cents  INTEGER NOT NULL CHECK (price_cents > 0)
);

CREATE TABLE customers (
  id         INTEGER PRIMARY KEY,
  full_name  TEXT NOT NULL,
  email      TEXT NOT NULL UNIQUE,
  city       TEXT NOT NULL
);

CREATE TABLE orders (
  id            INTEGER PRIMARY KEY,
  order_number  TEXT NOT NULL UNIQUE,
  customer_id   INTEGER NOT NULL REFERENCES customers (id),
  placed_on     DATE NOT NULL,
  -- NULL while the parcel is still in transit
  delivered_on  DATE CHECK (delivered_on IS NULL OR delivered_on >= placed_on),
  total_cents   INTEGER NOT NULL CHECK (total_cents >= 0)
);
CREATE INDEX orders_customer_idx ON orders (customer_id);

CREATE TABLE order_items (
  id                INTEGER PRIMARY KEY,
  order_id          INTEGER NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id        INTEGER NOT NULL REFERENCES products (id),
  quantity          INTEGER NOT NULL CHECK (quantity > 0),
  unit_price_cents  INTEGER NOT NULL CHECK (unit_price_cents >= 0),
  serial_number     TEXT
);
CREATE INDEX order_items_order_idx ON order_items (order_id);
CREATE INDEX order_items_product_idx ON order_items (product_id);

CREATE TABLE claims (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           TEXT NOT NULL UNIQUE,
  order_item_id  INTEGER NOT NULL REFERENCES order_items (id) ON DELETE CASCADE,
  type           TEXT NOT NULL CHECK (type IN ('withdrawal', 'warranty')),
  reason         TEXT NOT NULL CHECK (reason IN (
                   'no_reason', 'changed_mind', 'not_as_described', 'ordered_by_mistake',
                   'better_price', 'arrived_late', 'does_not_turn_on', 'battery', 'screen',
                   'audio', 'connectivity', 'charging', 'physical_defect', 'other')),
  description    TEXT NOT NULL DEFAULT '',
  status         TEXT NOT NULL DEFAULT 'received' CHECK (status IN (
                   'received', 'approved', 'product_returned', 'replaced', 'refunded', 'rejected')),
  -- Calendar day (Europe/Madrid) the shop was informed; deadlines count from here.
  opened_on      DATE NOT NULL,
  -- Refund deadline for withdrawals (art. 107.1), internal target for warranty claims.
  due_on         DATE NOT NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  closed_at      TIMESTAMPTZ,
  CHECK ((status IN ('replaced', 'refunded', 'rejected')) = (closed_at IS NOT NULL)),
  CHECK (NOT (type = 'withdrawal' AND status = 'replaced'))
);
-- A product line can only have one open claim at a time.
CREATE UNIQUE INDEX claims_one_open_per_item ON claims (order_item_id)
  WHERE status IN ('received', 'approved', 'product_returned');
CREATE INDEX claims_status_idx ON claims (status);
CREATE INDEX claims_due_idx ON claims (due_on);

CREATE TABLE claim_events (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  claim_id     INTEGER NOT NULL REFERENCES claims (id) ON DELETE CASCADE,
  kind         TEXT NOT NULL CHECK (kind IN ('created', 'status_changed', 'internal_note')),
  actor        TEXT NOT NULL CHECK (actor IN ('customer', 'staff', 'system')),
  from_status  TEXT,
  to_status    TEXT,
  message      TEXT,
  -- Public events are shown to the customer on the tracking page; notes are not.
  is_public    BOOLEAN NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (kind <> 'internal_note' OR is_public = FALSE)
);
CREATE INDEX claim_events_claim_idx ON claim_events (claim_id, created_at);

-- Small key/value table for app state such as when the demo data was generated.
CREATE TABLE app_meta (
  key         TEXT PRIMARY KEY,
  value       TEXT NOT NULL,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
